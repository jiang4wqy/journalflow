"""Generate relocatable-by-rerun project MCP configuration without global edits."""
from __future__ import annotations

import json
import sys
import tomllib
from pathlib import Path

MARKER = '# Generated by JournalFlow; rerun connect-codex after moving this project.'


def connect(config, *, python=None, server_script=None):
    python = Path(python or sys.executable).resolve()
    script = Path(server_script or Path(__file__).resolve().parents[2] / 'scripts/serve-mcp.py').resolve()
    if not python.is_file() or (server_script is not None and not script.is_file()):
        raise ValueError('The Python executable or explicit server entry is missing')
    target = config.path.parent / '.codex/config.toml'
    if target.exists():
        old = target.read_text(encoding='utf-8')
        values = tomllib.loads(old)
        if (not old.startswith(MARKER + '\n') or set(values) != {'mcp_servers'} or
                set(values['mcp_servers']) != {'journalflow'} or
                set(values['mcp_servers']['journalflow']) != {
                    'command', 'args', 'cwd', 'startup_timeout_sec', 'tool_timeout_sec'}):
            raise ValueError('Existing project configuration preserved; merge the MCP entry manually')
    def quote(path):
        return json.dumps(path.as_posix(), ensure_ascii=False)
    arguments = ['-I', '-X', 'utf8', script.as_posix(), '--config', config.path.as_posix()] if script.is_file() else [
        '-I', '-X', 'utf8', '-m', 'journalflow', '--config', config.path.as_posix(), 'mcp']
    text = (MARKER + '\n[mcp_servers.journalflow]\n' + f'command = {quote(python)}\n' +
            'args = ' + json.dumps(arguments, ensure_ascii=False) + '\n' +
            f'cwd = {quote(config.path.parent)}\nstartup_timeout_sec = 120\ntool_timeout_sec = 300\n')
    target.parent.mkdir(parents=True, exist_ok=True)
    temporary = target.with_suffix('.tmp')
    temporary.write_text(text, encoding='utf-8')
    temporary.replace(target)
    return {'config': str(target), 'codex_project': str(config.path.parent), 'server': 'journalflow',
            'global_configuration_modified': False, 'restart_project_connection': True}
